/** Escapes text for safe embedding in XML/RSS — server names and finding
 * text come from scanned registry data, not text mcphound wrote itself. */
export function escapeXml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}
